-- FAX・メールアドレスのNULL状態を確認
SELECT
  KOKYAKUCD,
  KOKYAKUNAME,
  FAX,
  MAIL
FROM KOKYAKUKOJIN_TABLE
ORDER BY KOKYAKUCD;

-- 個人顧客の認証情報が登録されているか確認
SELECT
  K.KOKYAKUCD,
  K.KOKYAKUNAME,
  CASE
    WHEN P.KOKYAKUCD IS NULL THEN '認証情報なし'
    ELSE '認証情報あり'
  END AS AUTH_STATUS
FROM KOKYAKUKOJIN_TABLE K
LEFT JOIN KOKYAKUPASS_TABLE P
  ON K.KOKYAKUCD = P.KOKYAKUCD
ORDER BY K.KOKYAKUCD;

