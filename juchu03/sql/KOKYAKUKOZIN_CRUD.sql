-- 3. SELECT：顧客コードで取得
SELECT *
FROM KOKYAKUKOZIN
WHERE KOKYAKUCD = '400001';

-- 4. SELECT：メールアドレスで取得
SELECT *
FROM KOKYAKUKOZIN
WHERE MAIL = 'yamada@example.com';

-- 5. SELECT：ログイン認証用
SELECT K.KOKYAKUCD, K.KOKYAKUNAME, K.MAIL,
       K.YOSIN_GENDO, K.URIKAKE_ZAN
FROM KOKYAKUKOZIN K
INNER JOIN KOKYAKUPASS_TABLE P
        ON P.KOKYAKUCD = K.KOKYAKUCD
WHERE K.KOKYAKUCD = '400001'
  AND P.PASSWORD = 'password';

-- 6. SELECT：個人顧客一覧
SELECT KOKYAKUCD, KOKYAKUNAME, MAIL, TEL,
       YOSIN_GENDO, URIKAKE_ZAN
FROM KOKYAKUKOZIN
ORDER BY KOKYAKUCD;
