-- 1. CREATE
CREATE TABLE IF NOT EXISTS KOKYAKUKOZIN (
    KOKYAKUCD   VARCHAR(10)  NOT NULL PRIMARY KEY,
    KOKYAKUNAME VARCHAR(100) NOT NULL,
    KOKYAKUKANA VARCHAR(100) NOT NULL,
    ZIP         VARCHAR(8) NOT NULL,
    KENCD       VARCHAR(2) NOT NULL,
    ADDRESS1    VARCHAR(200),
    ADDRESS2    VARCHAR(200),
    TEL         VARCHAR(20),
    FAX         VARCHAR(20),
    MAIL        VARCHAR(254) UNIQUE,
    URIKAKE_ZAN INT NOT NULL DEFAULT 0,
    YOSIN_GENDO INT NOT NULL DEFAULT 1000000,
    EIGYOUSHOCD VARCHAR(4),
    TOUROKU_D   DATE NOT NULL,
    BIRTHDAY    DATE,
    CONSTRAINT CK_KOKYAKUKOZIN_CD
        CHECK (SUBSTRING(KOKYAKUCD, 1, 1) IN ('4', '5', '6', '7', '8')),
    CONSTRAINT CK_KOKYAKUKOZIN_YOSIN
        CHECK (YOSIN_GENDO = 1000000)
);
ALTER TABLE KOKYAKUKOZIN ADD COLUMN IF NOT EXISTS BIRTHDAY DATE;

-- 個人顧客コード採番の初期値
MERGE INTO CTR_CURCODE_TABLE (CODENAME, DATANAME, CURCODE)
KEY (DATANAME)
VALUES ('個人顧客コード', 'KOKYAKUKOZIN', '400000');

